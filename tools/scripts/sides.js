export function sideEvent(name, api, ev) {
  if (name !== 'block') return;
  const b = ev.block, pl = ev.player;
  for (const [id, c] of Object.entries(CHAINS)) {
    for (const [slot, flag] of c.steps) {
      if (api.flag(flag) || !api.isSlot(b, slot)) continue;
      // Игрок мог наткнуться на тайник сам: тогда цепочка начинается с него
      if (!api.seen(id)) api.start(id);
      if (api.done(id)) continue;
      api.flag(flag, 1);
      pl.sendMessage(FOUND[flag]);
      if (!ALL(api, id)) continue;
      if (id === 'x_founder') {
        api.finish(id);
        for (const p of api.players()) p.onScreenDisplay.setTitle('§6Латы основателя', { subtitle: 'Наденьте все четыре части', fadeInDuration: 10, stayDuration: 70, fadeOutDuration: 20 });
        api.tell('§6Латы князя Всеслава и меч «Заря» собраны. В полном комплекте — сила, крепость и защита от огня; «Заря» жжёт нежить.');
      } else api.tell('§6' + c.after);
    }
  }
  if (api.isSlot(b, 'forge_ledger') && !api.flag('forge_ledger')) { api.flag('forge_ledger', 1); pl.sendMessage('§7Счёт оружия: клинки замка продавал людям Рыжего казначей. Кузнецу Гордею будет что сказать.'); }
  if (api.isSlot(b, 'porch_book') && !api.flag('klim_notes')) { api.flag('klim_notes', 1); pl.sendMessage('§7Записки привратника Клима: он видел, кто гнался за княжичем в ночь пира.'); }
}

