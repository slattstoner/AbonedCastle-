const ALL = (api, id) => CHAINS[id].steps.every(([, f]) => api.flag(f));
const nextStep = (api, id) => CHAINS[id].steps.find(([, f]) => !api.flag(f));

export const SIDE_QUESTS = {};
for (const [id, c] of Object.entries(CHAINS)) {
  SIDE_QUESTS[id] = {
    title: c.title,
    hint: (api) => { const st = nextStep(api, id); return st ? st[3] : c.after || 'Всё найдено.'; },
    target: (api) => {
      const st = nextStep(api, id);
      if (st && api.castle.slots[st[0]]) return { at: api.castle.slots[st[0]], label: st[2] };
      if (id === 'x_watch') return { at: [63, 0, 126], label: 'Митька у ворот' };
      if (id === 'x_hunt') return { path: 'home_agafya', label: 'Кухня' };
      return null;
    },
  };
}

